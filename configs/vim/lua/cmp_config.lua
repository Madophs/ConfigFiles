-- Use buffer source for `/` and `?` (if you enabled `native_menu`, this won't work anymore).
cmp.setup.cmdline({ '/', '?' }, {
  mapping = cmp.mapping.preset.cmdline(),
  sources = {
    { name = 'buffer' }
  }
})

-- Use cmdline & path source for ':' (if you enabled `native_menu`, this won't work anymore).
cmp.setup.cmdline(':', {
  mapping = cmp.mapping.preset.cmdline(),
  sources = cmp.config.sources({
    { name = 'path' }
  }, {
    { name = 'cmdline' }
  }),
  matching = { disallow_symbol_nonprefix_matching = false }
})

-- Set up lspconfig.
local capabilities = require('cmp_nvim_lsp').default_capabilities()
-- Replace <YOUR_LSP_SERVER> with each lsp server you've enabled.
vim.lsp.config('clangd', {
  capabilities = capabilities
})
vim.lsp.config('lua_ls', {
  capabilities = capabilities,
})
vim.lsp.config('bashls', {
  capabilities = capabilities,
  -- Explicitly ensure single file support is active if fallback fails
  single_file_support = true,
  root_dir = function(bufnr, on_dir)
    -- Look for .git upward from the active buffer
    local root = vim.fs.root(bufnr, { '.git' })

    -- Fallback to current working directory if .git isn't found
    local final_root = root or vim.fn.getcwd()

    -- Crucial: You MUST invoke the on_dir callback or the LSP will never start!
    on_dir(final_root)
  end,
  settings = {
    bashIde = {
      -- These options tell bashls how deep to look for files to source definitions
      globPattern = "**/*@(.sh|.inc|.bash|.command)",
    }
  }
})
